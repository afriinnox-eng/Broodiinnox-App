export function t(key, lang = 'en', vars = {}) {
  const table = DICT[lang] || DICT.en;
  let s = table[key] ?? DICT.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function fmtMoney(n, lang = 'en') {
  const fmt = new Intl.NumberFormat(lang === 'fr' ? 'fr-FR' : 'en-US', { maximumFractionDigits: 0 });
  return `RWF ${fmt.format(n)}`;
}

export function fmtTemp(c, unit = 'C') {
  return unit === 'F' ? `${Math.round((c * 9) / 5 + 32)}°F` : `${c.toFixed(1)}°C`;
}
